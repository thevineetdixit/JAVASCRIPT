//for loop
for(let i=1; i<=5; i++){
    console.log("Iteration number: " + i);
}   



//while loop
let j = 1;
while(j <= 5){
    console.log("While loop iteration: " + j);
    j++;
}


//nested loops
for(let a=1; a<=3; a++){
    for(let b=1; b<=2; b++){
        console.log("a: " + a + ", b: " + b);
    }
}

